<#
 Imports Material Symbols Rounded icons (weight 400, outline, 24px) from Google's open-source repository
 (https://github.com/google/material-design-icons, Apache-2.0) and regenerates
 src/AvasRoutingTool/Resources/MaterialIcons.xaml as 24 x 24 Geometry resources keyed MIcon.<name>.
 Idempotent: SVGs already in tools/icons/svg are not downloaded again (use -Force to refresh).
 Only raw.githubusercontent.com is contacted. Run from anywhere:  pwsh tools/icons/import-material-icons.ps1
#>
param([switch]$Force)
$ErrorActionPreference = 'Stop'

$Names = @(
    'settings','sync','light_mode','dark_mode','cleaning_services','folder_open','edit','info','play_arrow','stop','check',
    'lock','expand_more','content_copy','grid_view','power_settings_new','desktop_windows','videocam','chevron_left',
    'chevron_right','close','warning'
)

. (Join-Path $PSScriptRoot 'SvgPathConverter.ps1')

$svgDir = Join-Path $PSScriptRoot 'svg'
$outFile = Join-Path $PSScriptRoot '..\..\src\AvasRoutingTool\Resources\MaterialIcons.xaml'
New-Item -ItemType Directory -Force $svgDir | Out-Null

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('<ResourceDictionary xmlns="http://schemas.microsoft.com/winfx/2006/xaml/presentation"')
[void]$sb.AppendLine('                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('    <!-- GENERATED by tools/icons/import-material-icons.ps1 - do not edit by hand.')
[void]$sb.AppendLine('         Material Symbols Rounded, weight 400, outline, 24px (Apache-2.0, see THIRD-PARTY-NOTICES.md).')
[void]$sb.AppendLine('         Geometry is in a 24 x 24 box; MaterialIcon scales it. Fill rule is NonZero (the F1 prefix; WPF defaults to EvenOdd). -->')
[void]$sb.AppendLine('')

foreach ($name in $Names) {
    $file = Join-Path $svgDir "$name.svg"
    if ($Force -or -not (Test-Path $file)) {
        $url = "https://raw.githubusercontent.com/google/material-design-icons/master/symbols/web/$name/materialsymbolsrounded/${name}_24px.svg"
        Write-Host "Downloading $url"
        Invoke-WebRequest -Uri $url -OutFile $file -UseBasicParsing
    }
    $svg = [xml](Get-Content -Raw -Encoding UTF8 $file)
    if ($svg.svg.viewBox -ne '0 -960 960 960') { throw "$name.svg: unexpected viewBox '$($svg.svg.viewBox)'" }
    $paths = @($svg.svg.path)
    if ($paths.Count -lt 1) { throw "$name.svg: no <path>" }
    foreach ($p in $paths) { if ($p.'fill-rule' -eq 'evenodd') { throw "$name.svg: evenodd fill rule is not supported by this generator" } }
    $d = 'F1 ' + (($paths | ForEach-Object { ConvertTo-Material24Path $_.d }) -join ' ')
    [void]$sb.AppendLine("    <Geometry x:Key=`"MIcon.$name`">$d</Geometry>")
}
[void]$sb.AppendLine('')
[void]$sb.AppendLine('</ResourceDictionary>')

$utf8 = New-Object System.Text.UTF8Encoding($false)
[System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($outFile), $sb.ToString().Replace("`r`n","`n"), $utf8)
Write-Host "Wrote $($Names.Count) icons to $outFile"
